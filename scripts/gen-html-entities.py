#!/usr/bin/env python3
"""Generates core/src/html_entities.h: the 252 HTML 4 named character references, sorted by name (developers only; the
output is committed).   python3 scripts/gen-html-entities.py > core/src/html_entities.h"""
from html.entities import name2codepoint

print("#pragma once")
print("// GENERATED by scripts/gen-html-entities.py (HTML 4 named character references, sorted for binary search); do not edit.")
print("namespace pbo {\nnamespace html_entities {\n")
print("struct Entity { const char* name; unsigned code; };")
print(f"inline constexpr Entity kEntities[{len(name2codepoint)}] = {{")
for name in sorted(name2codepoint):
    print(f'    {{"{name}", 0x{name2codepoint[name]:04X}}},')
print("};\n\n}  // namespace html_entities\n}  // namespace pbo")
