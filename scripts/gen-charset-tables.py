#!/usr/bin/env python3
"""Generates core/src/charset_tables.h from Python's codecs (developers only; the output is committed).
   python3 scripts/gen-charset-tables.py > core/src/charset_tables.h"""
import codecs

def table(codec, start, end):
    out = []
    for b in range(start, end + 1):
        try:
            out.append(ord(bytes([b]).decode(codec)))
        except UnicodeDecodeError:
            out.append(0xFFFD)
    return out

def emit(name, values, start):
    print(f"// {name}: code points of the bytes 0x{start:02X}..0x{start + len(values) - 1:02X}; 0xFFFD = undefined")
    print(f"inline constexpr unsigned short {name}[{len(values)}] = {{")
    for i in range(0, len(values), 8):
        print("    " + ", ".join(f"0x{v:04X}" for v in values[i:i + 8]) + ",")
    print("};\n")

print("#pragma once")
print("// GENERATED by scripts/gen-charset-tables.py from Python's codecs; do not edit.")
print("namespace pbo {\nnamespace charset_tables {\n")
emit("kIso8859_2", table("iso8859_2", 0xA0, 0xFF), 0xA0)
emit("kIso8859_15", table("iso8859_15", 0xA0, 0xFF), 0xA0)
emit("kWindows1250", table("cp1250", 0x80, 0xFF), 0x80)
emit("kWindows1252", table("cp1252", 0x80, 0x9F), 0x80)
print("}  // namespace charset_tables\n}  // namespace pbo")
